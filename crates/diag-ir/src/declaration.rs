pub use generated::diag::ir::*;

use crate::IR_SCHEMA_VERSION;

/// Limits the verifier applies to a document before it is read. A document reaches the agent
/// from a signed manifest (8.2.6), but the verifier is the only defence against a malformed one
/// past that point, so the limits bound the work and the recursion it may cause: nested layouts
/// are themselves limited to 16 levels by the decoder (ADR-242), well within `max_depth`.
pub const VERIFIER_OPTIONS: flatbuffers::VerifierOptions = flatbuffers::VerifierOptions {
    max_depth: 64,
    max_tables: 1_000_000,
    max_apparent_size: 1 << 31,
    ignore_missing_null_terminator: false,
};

/// Why [`load_ecu_document`] rejected a buffer.
#[derive(Debug, Error, PartialEq)]
pub enum LoadError {
    /// The buffer is too short to hold a FlatBuffers root offset and file identifier.
    #[error("buffer of {0} bytes is too short for an IR document")]
    TooShort(usize),
    /// The file identifier is not `DIR1` (`ir.fbs`), so the buffer is not an IR document.
    #[error("buffer is not an IR document (file identifier is not {ECU_DOCUMENT_IDENTIFIER})")]
    WrongIdentifier,
    /// The FlatBuffers verifier rejected the buffer.
    #[error("malformed IR document: {0}")]
    Malformed(#[from] flatbuffers::InvalidFlatbuffer),
    /// The document was written for another IR schema version (8.2.6). Until the first release
    /// no other version is read (ADR-281 item 4).
    #[error("IR schema version {found} is not supported (expected {expected})")]
    SchemaVersion {
        /// The version the document carries.
        found: u32,
        /// The version this build reads ([`IR_SCHEMA_VERSION`]).
        expected: u32,
    },
}

/// The length of a FlatBuffers root offset followed by a file identifier.
const HEADER_LEN: usize = 4 + flatbuffers::FILE_IDENTIFIER_LENGTH;

/// Checks a buffer and returns its `EcuDocument`.
///
/// The buffer must carry the `DIR1` file identifier, pass the FlatBuffers verifier with
/// [`VERIFIER_OPTIONS`], and declare [`IR_SCHEMA_VERSION`]. Only then are its fields read; the
/// returned document borrows `buf` and its accessors do not fail.
pub fn load_ecu_document(buf: &[u8]) -> Result<EcuDocument<'_>, LoadError> {
    // `buffer_has_identifier` slices the identifier out without checking the length.
    if buf.len() < HEADER_LEN {
        return Err(LoadError::TooShort(buf.len()));
    }
    if !ecu_document_buffer_has_identifier(buf) {
        return Err(LoadError::WrongIdentifier);
    }
    let document = root_as_ecu_document_with_opts(&VERIFIER_OPTIONS, buf)?;
    if document.schema_version() != IR_SCHEMA_VERSION {
        return Err(LoadError::SchemaVersion {
            found: document.schema_version(),
            expected: IR_SCHEMA_VERSION,
        });
    }
    Ok(document)
}

/// Encodes a document with the `DIR1` file identifier, as the frontends write it.
pub fn encode_ecu_document(document: &EcuDocumentT) -> Vec<u8> {
    let mut builder = flatbuffers::FlatBufferBuilder::new();
    let root = document.pack(&mut builder);
    finish_ecu_document_buffer(&mut builder, root);
    builder.finished_data().to_vec()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn document() -> EcuDocumentT {
        let field = FieldT {
            id: 1,
            short_name: Some("vin".into()),
            bit_offset: 24,
            bit_length: 136,
            kind: DataKind::Ascii,
            ..Default::default()
        };
        let service = ServiceT {
            id: 1,
            short_name: Some("vin.read".into()),
            request: Some(Box::new(RequestT {
                sid: 0x22,
                prefix: Some(vec![0xF1, 0x90]),
                ..Default::default()
            })),
            positive: Some(Box::new(PositiveResponseT {
                sid: 0x62,
                prefix: Some(vec![0xF1, 0x90]),
                fields: Some(vec![field]),
            })),
            ..Default::default()
        };
        let variant = EcuVariantT {
            id: 7,
            short_name: Some("exampleEcuV1".into()),
            part_numbers: Some(vec!["NGR-EX-0001".into()]),
            services: Some(vec![service]),
            ..Default::default()
        };
        EcuDocumentT {
            schema_version: IR_SCHEMA_VERSION,
            source_format: Some("csv-starlark".into()),
            source_digest: Some("00".repeat(32)),
            variant: Some(Box::new(variant)),
            procedure: Some(vec![1, 2, 3]),
        }
    }

    #[test]
    fn an_encoded_document_loads_and_reads_back() {
        let buf = encode_ecu_document(&document());
        let loaded = load_ecu_document(&buf).expect("loads");
        assert_eq!(loaded.unpack(), document());

        let service = loaded.variant().unwrap().services().unwrap().get(0);
        assert_eq!(service.short_name(), Some("vin.read"));
        let field = service.positive().unwrap().fields().unwrap().get(0);
        assert_eq!(field.bit_offset(), 24);
        assert_eq!(field.kind(), DataKind::Ascii);
        // Defaults the schema gives a field that was not written.
        assert_eq!(field.placement(), Placement::Absolute);
        assert_eq!(field.byte_order(), ByteOrder::Big);
        assert_eq!(service.p2_millis(), 50);
    }

    #[test]
    fn a_buffer_too_short_for_the_header_is_rejected() {
        for len in 0..HEADER_LEN {
            assert_eq!(
                load_ecu_document(&vec![0; len]).unwrap_err(),
                LoadError::TooShort(len)
            );
        }
    }

    #[test]
    fn another_file_identifier_is_rejected() {
        let mut buf = encode_ecu_document(&document());
        buf[4..8].copy_from_slice(b"XIR1");
        assert_eq!(
            load_ecu_document(&buf).unwrap_err(),
            LoadError::WrongIdentifier
        );
    }

    #[test]
    fn another_schema_version_is_rejected() {
        for version in [0, IR_SCHEMA_VERSION - 1, IR_SCHEMA_VERSION + 1] {
            let mut doc = document();
            doc.schema_version = version;
            let buf = encode_ecu_document(&doc);
            assert_eq!(
                load_ecu_document(&buf).unwrap_err(),
                LoadError::SchemaVersion {
                    found: version,
                    expected: IR_SCHEMA_VERSION
                }
            );
        }
    }

    #[test]
    fn a_root_offset_past_the_end_is_rejected_by_the_verifier() {
        let mut buf = encode_ecu_document(&document());
        let len = u32::try_from(buf.len()).unwrap();
        buf[0..4].copy_from_slice(&len.to_le_bytes());
        assert!(matches!(
            load_ecu_document(&buf),
            Err(LoadError::Malformed(_))
        ));
    }

    #[test]
    fn a_truncated_document_is_rejected_or_unchanged() {
        // Cutting only trailing padding loses nothing, so such a buffer still reads as the same
        // document; any cut into data is rejected.
        let buf = encode_ecu_document(&document());
        for len in HEADER_LEN..buf.len() {
            if let Ok(doc) = load_ecu_document(&buf[..len]) {
                assert_eq!(doc.unpack(), document(), "length {len}");
            }
        }
        assert!(load_ecu_document(&buf[..buf.len() / 2]).is_err());
    }

    #[test]
    fn a_corrupted_document_is_rejected_or_read_without_panicking() {
        // Every single-byte change is either rejected or yields a document whose accessors are
        // safe to call: the verifier is what makes reading an untrusted buffer sound.
        let buf = encode_ecu_document(&document());
        for at in HEADER_LEN..buf.len() {
            for value in [0x00, 0x7F, 0x80, 0xFF] {
                let mut corrupted = buf.clone();
                corrupted[at] = value;
                if let Ok(doc) = load_ecu_document(&corrupted) {
                    let _ = doc.unpack();
                }
            }
        }
    }
}
